// Decompile ReadStream_QueueBuffersThread and related streaming functions.
// Target addresses (Ghidra VAs = ELF VA + 0x100000):
//
// ReadStream_QueueBuffersThread: ELF 0x02d93900 -> Ghidra 0x02e93900
// on_libusb_transfer_complete: found via xref
// TransferQueue constructor: found via xref
// BulkReadStream_Read: found via string xref
// StopBulkReadStream: found via string xref
//
// Usage: ghidra-analyzeHeadless <project_dir> <project_name> -process -noanalysis \
//   -scriptPath re/ghidra/scripts -postScript DecompileStreamingThread.java
//
// @category USB

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.symbol.Symbol;
import ghidra.program.model.symbol.SymbolIterator;
import ghidra.program.model.symbol.SymbolTable;

import java.io.File;
import java.io.FileWriter;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.List;

public class DecompileStreamingThread extends GhidraScript {

    // Known Ghidra addresses (ELF VA + 0x100000)
    private static final long[] KNOWN_ADDRESSES = {
        0x02e93900L,  // ReadStream_QueueBuffersThread
    };

    // Function name substrings to search for
    private static final String[] NAME_PATTERNS = {
        "ReadStream_QueueBuffersThread",
        "on_libusb_transfer_complete",
        "TransferQueue",
        "BulkReadStream_Read",
        "BulkReadStream_Request",
        "StopBulkReadStream",
    };

    @Override
    public void run() throws Exception {
        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setSimplificationStyle("decompile");

        FunctionManager fm = currentProgram.getFunctionManager();
        List<Function> targets = new ArrayList<>();

        // 1. Find functions at known addresses
        for (long addr : KNOWN_ADDRESSES) {
            Address ghidraAddr = currentProgram.getAddressFactory()
                .getDefaultAddressSpace().getAddress(addr);
            Function f = fm.getFunctionAt(ghidraAddr);
            if (f != null) {
                targets.add(f);
                println("Found at known address: " + f.getName() + " @ " + f.getEntryPoint());
            } else {
                println("No function at Ghidra address 0x" + Long.toHexString(addr));
                // Try to find function containing that address
                f = fm.getFunctionContaining(ghidraAddr);
                if (f != null) {
                    targets.add(f);
                    println("  Found containing function: " + f.getName() + " @ " + f.getEntryPoint());
                }
            }
        }

        // 2. Find functions by name pattern
        FunctionIterator funcs = fm.getFunctions(true);
        while (funcs.hasNext()) {
            Function f = funcs.next();
            String name = f.getName();
            for (String pattern : NAME_PATTERNS) {
                if (name.contains(pattern)) {
                    boolean already = false;
                    for (Function existing : targets) {
                        if (existing.getEntryPoint().equals(f.getEntryPoint())) {
                            already = true;
                            break;
                        }
                    }
                    if (!already) {
                        targets.add(f);
                        println("Found by name: " + name + " @ " + f.getEntryPoint());
                    }
                    break;
                }
            }
        }

        println("Total functions to decompile: " + targets.size());

        // 3. Decompile and write output
        String outPath = System.getProperty("user.home") +
            "/nvidia/saleae_reverse/re/ghidra/decompiled-streaming-thread.txt";
        PrintWriter out = new PrintWriter(new FileWriter(outPath));

        out.println("// Decompiled streaming thread functions from libgraph_server_shared.so");
        out.println("// Generated by DecompileStreamingThread.java");
        out.println("// Ghidra addresses = ELF VA + 0x100000");
        out.println("// " + new java.util.Date());
        out.println();

        for (Function f : targets) {
            out.println("// ========================================================================");
            out.println("// Function: " + f.getName());
            out.println("// Address:  " + f.getEntryPoint() + " (ELF VA: 0x" +
                Long.toHexString(f.getEntryPoint().getOffset() - 0x100000) + ")");
            out.println("// Size:     " + f.getBody().getNumAddresses() + " bytes");
            out.println("// ========================================================================");
            out.println();

            DecompileResults result = decomp.decompileFunction(f, 120, monitor);
            if (result.decompileCompleted()) {
                out.println(result.getDecompiledFunction().getC());
            } else {
                out.println("// DECOMPILATION FAILED: " + result.getErrorMessage());
            }
            out.println();
        }

        out.close();
        decomp.dispose();

        println("Output written to: " + outPath);
    }
}
