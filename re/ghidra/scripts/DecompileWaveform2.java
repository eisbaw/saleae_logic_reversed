// Decompile specific waveform serialization/deserialization functions by address
// @category Analysis
// @author claude

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;

import java.io.File;
import java.io.PrintWriter;

public class DecompileWaveform2 extends GhidraScript {

    // Ghidra VAs (ELF VA + 0x100000) for specific functions of interest
    private static final long[] FUNC_ADDRS = {
        // WaveformStoreNode::Serialize (called from SerializeOnThread)
        0x2d8f920L,

        // WaveformStoreNode::Deserialize (called from DeserializeOnThread)
        0x2d8fd20L,

        // WaveformStoreNode::UpdateApi (called after successful deserialization)
        0x2d92050L,

        // WaveformDataCollection::WaveformDataCollection (constructor)
        // - from PRETTY_FUNCTION string at 0x462247
        // Need to find it via callers. Try the cereal serialize template
        // WaveformDataCollection::serialize<SaleaeBinaryInputArchive>
        // WaveformDataCollection::serialize<SaleaeBinaryOutputArchive>

        // PackedWaveformGetStats
        // - from PRETTY_FUNCTION at 0x488b96

        // WaveformDataCollection::Writer::PushBack
        // - from PRETTY_FUNCTION at 0x4fb621

        // FUN_02d8c350 - status update function (serialize/deserialize progress)
        0x2d8c350L,

        // FUN_02d80730 - SetApi helper
        0x2d80730L,
    };

    @Override
    public void run() throws Exception {
        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setSimplificationStyle("decompile");

        FunctionManager funcMgr = currentProgram.getFunctionManager();

        String outPath = System.getProperty("user.dir") + "/re/ghidra/decompiled-waveform2.txt";
        File outFile = new File(outPath);
        PrintWriter pw = new PrintWriter(outFile);

        pw.println("// ================================================================");
        pw.println("// Decompiled waveform serialize/deserialize functions (targeted)");
        pw.println("// Saleae Logic 2 v2.4.40 - libgraph_server_shared.so");
        pw.println("// Generated by DecompileWaveform2.java");
        pw.println("// ================================================================");
        pw.println();

        int count = 0;
        for (long addr : FUNC_ADDRS) {
            Address funcAddr = toAddr(addr);
            Function func = funcMgr.getFunctionAt(funcAddr);
            if (func == null) {
                // Try to find function containing this address
                func = funcMgr.getFunctionContaining(funcAddr);
            }
            if (func == null) {
                pw.println("// FUNCTION NOT FOUND at Ghidra VA 0x" + Long.toHexString(addr));
                pw.println("// ELF VA: 0x" + Long.toHexString(addr - 0x100000L));
                pw.println();
                continue;
            }

            long elfVA = func.getEntryPoint().getOffset() - 0x100000L;
            pw.println("// ----------------------------------------------------------------");
            pw.println("// Function at Ghidra VA 0x" + Long.toHexString(func.getEntryPoint().getOffset()));
            pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
            pw.println("// Name: " + func.getName());
            pw.println("// Size: " + func.getBody().getNumAddresses() + " bytes");
            pw.println("// ----------------------------------------------------------------");

            DecompileResults results = decomp.decompileFunction(func, 120, monitor);
            if (results.decompileCompleted()) {
                pw.println(results.getDecompiledFunction().getC());
            } else {
                pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
            }
            pw.println();
            count++;
        }

        // Also find and decompile functions that these call
        pw.println("// ================================================================");
        pw.println("// CALLEES of serialize/deserialize functions");
        pw.println("// ================================================================");
        pw.println();

        // Decompile callees of FUN_02d8f920 (serialize) and FUN_02d8fd20 (deserialize)
        for (long parentAddr : new long[]{0x2d8f920L, 0x2d8fd20L}) {
            Address funcAddr = toAddr(parentAddr);
            Function func = funcMgr.getFunctionAt(funcAddr);
            if (func == null) continue;

            for (Function callee : func.getCalledFunctions(monitor)) {
                // Skip library functions
                if (callee.getName().startsWith("std::") || callee.getName().startsWith("operator")) continue;
                if (callee.getName().startsWith("__cxa")) continue;
                if (callee.getName().startsWith("thunk_")) continue;
                // Skip very small functions (likely thunks)
                if (callee.getBody().getNumAddresses() < 20) continue;

                long elfVA = callee.getEntryPoint().getOffset() - 0x100000L;
                pw.println("// ----------------------------------------------------------------");
                pw.println("// Callee at Ghidra VA 0x" + Long.toHexString(callee.getEntryPoint().getOffset()));
                pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
                pw.println("// Name: " + callee.getName());
                pw.println("// Size: " + callee.getBody().getNumAddresses() + " bytes");
                pw.println("// Called from: 0x" + Long.toHexString(parentAddr - 0x100000L));
                pw.println("// ----------------------------------------------------------------");

                DecompileResults results = decomp.decompileFunction(callee, 120, monitor);
                if (results.decompileCompleted()) {
                    pw.println(results.getDecompiledFunction().getC());
                } else {
                    pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
                }
                pw.println();
                count++;
            }
        }

        pw.close();
        decomp.dispose();
        println("Decompiled " + count + " functions to: " + outPath);
    }
}
