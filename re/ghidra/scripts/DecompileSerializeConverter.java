// Decompile SerializeConverter specializations for driver-relevant types
// Finds xrefs to type name strings and decompiles referencing functions
//@category RE
import ghidra.app.decompiler.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.*;
import ghidra.program.model.address.*;
import ghidra.program.model.symbol.*;

import java.util.*;

public class DecompileSerializeConverter extends GhidraScript {
    @Override
    public void run() throws Exception {
        // ELF VA + 0x100000 = Ghidra VA for type name strings
        String[][] stringAddrs = new String[][] {
            // {Ghidra VA, description}
            {"0x476ac3", "Saleae::Graph::CalibrationData"},
            {"0x52d392", "Saleae::Graph::SamplingConfigurationData"},
            {"0x518a13", "Saleae::Graph::LogicDevice::SetSampleRate"},
            {"0x4828b9", "Saleae::Graph::LogicDevice::EnableChannels"},
            {"0x4d1c13", "Saleae::Graph::LogicDevice::StartCapture"},
            {"0x4d8828", "Saleae::Graph::LogicDevice::SettingResponse"},
            {"0x4fc4ad", "Saleae::Graph::LogicDevice::StopCapture"},
            {"0x5034fd", "Saleae::Graph::LogicDevice::SetDigitalVoltageThreshold"},
            {"0x5122aa", "Saleae::Graph::LogicDevice::StartCaptureResponse"},
            {"0x5122db", "Saleae::Graph::LogicDevice::StopCaptureResponse"},
            {"0x49dfbf", "Saleae::Graph::LogicDevice::SetAdcFullScaleGain"},
            {"0x5276ba", "Saleae::Graph::LogicDevice::SetLed"},
            {"0x52768d", "Saleae::Graph::LogicDevice::LogicDeviceState"},
        };

        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setOptions(new DecompileOptions());

        AddressFactory af = currentProgram.getAddressFactory();
        FunctionManager fm = currentProgram.getFunctionManager();
        ReferenceManager rm = currentProgram.getReferenceManager();

        Set<Address> decompiled = new HashSet<>();

        println("// ================================================================");
        println("// Decompiled SerializeConverter specializations (driver-relevant)");
        println("// Saleae Logic 2 v2.4.40 - libgraph_server_shared.so");
        println("// Generated by DecompileSerializeConverter.java");
        println("// ================================================================");

        for (String[] entry : stringAddrs) {
            String addrStr = entry[0];
            String desc = entry[1];

            // Also try the original ELF VA + 0x100000 (some strings at different offsets)
            Address strAddr = af.getAddress(addrStr);
            if (strAddr == null) {
                println("// ERROR: Could not parse address " + addrStr);
                continue;
            }

            println("");
            println("// ================================================================");
            println("// Type: " + desc);
            println("// String at: " + addrStr);
            println("// ================================================================");

            // Search for references to this string and nearby addresses (+/- 8 bytes)
            List<Reference> allRefs = new ArrayList<>();
            for (int offset = -4; offset <= 4; offset++) {
                Address nearby = strAddr.add(offset);
                for (Reference r : rm.getReferencesTo(nearby)) {
                    allRefs.add(r);
                }
            }

            if (allRefs.isEmpty()) {
                println("// No xrefs found for " + desc);
                continue;
            }

            println("// Found " + allRefs.size() + " xrefs");

            for (Reference ref : allRefs) {
                Address fromAddr = ref.getFromAddress();
                Function func = fm.getFunctionContaining(fromAddr);
                if (func == null) continue;
                if (decompiled.contains(func.getEntryPoint())) continue;
                decompiled.add(func.getEntryPoint());

                // Compute ELF VA
                long ghidraVA = func.getEntryPoint().getOffset();
                long elfVA = ghidraVA - 0x100000;

                println("");
                println("// ----------------------------------------------------------------");
                println("// Function at Ghidra VA 0x" + Long.toHexString(ghidraVA));
                println("// ELF VA: 0x" + Long.toHexString(elfVA));
                println("// Name: " + func.getName());
                println("// Size: " + func.getBody().getNumAddresses() + " bytes");
                println("// Referenced string: " + desc);
                println("// ----------------------------------------------------------------");
                println("");

                DecompileResults res = decomp.decompileFunction(func, 30, monitor);
                if (res.decompileCompleted()) {
                    println(res.getDecompiledFunction().getC());
                } else {
                    println("// DECOMPILE FAILED: " + res.getErrorMessage());
                }
            }
        }

        decomp.dispose();
        println("");
        println("// ================================================================");
        println("// END OF DECOMPILATION");
        println("// ================================================================");
    }
}
