// Decompile functions related to packed_data_collection (slab, fixed_deque, deque_arena)
// @category Analysis
// @author claude

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.ReferenceIterator;
import ghidra.program.model.symbol.ReferenceManager;

import java.io.File;
import java.io.PrintWriter;
import java.util.LinkedHashSet;
import java.util.Set;

public class DecompilePackedData extends GhidraScript {

    // Ghidra VAs for assertion/PRETTY_FUNCTION strings
    // These are in .rodata, referenced by the functions we want to find
    private static final long[] STRING_ADDRS = {
        // Source file paths (used in assert __FILE__ macros)
        0x4abfd4L, // deque_arena.cpp
        0x511493L, // fixed_deque.cpp
        0x53aa82L, // slab.cpp
        0x53b5c0L, // fixed_deque.h

        // Assertion strings
        0x53aac8L, // slab.Size() == mSlabSize
        0x476b77L, // containing_slab != mSlabs.end()
        0x4d7bb0L, // slab allocation already suspended
        0x5265b5L, // slab allocation is not suspended

        // __PRETTY_FUNCTION__ strings
        0x454e3eL, // void Saleae::Graph::FixedByteDeque::EnsureCommitted(size_t)
        0x4622c9L, // void Saleae::Graph::DequeArena::FreeBefore(void *)
        0x502662L, // void *Saleae::Graph::DequeArena::AllocateContiguousExtend(size_t)
        0x4a4d5bL, // void Saleae::Graph::Slab::Manager::Return(Saleae::Graph::Slab)
        0x51f41fL, // Saleae::Graph::Slab::~Slab()
        0x53aae1L, // Saleae::Graph::FixedByteDeque::~FixedByteDeque()
        0x53430fL, // void Saleae::Graph::DequeArena::FreeAfter(void *)
        0x527335L, // typename FixedDeque<T>::Iterator ... operator--()
    };

    @Override
    public void run() throws Exception {
        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setSimplificationStyle("decompile");

        FunctionManager funcMgr = currentProgram.getFunctionManager();
        ReferenceManager refMgr = currentProgram.getReferenceManager();

        Set<Function> functions = new LinkedHashSet<>();

        // Find all functions referencing these strings
        for (long addr : STRING_ADDRS) {
            Address strAddr = toAddr(addr);
            ReferenceIterator refs = refMgr.getReferencesTo(strAddr);
            while (refs.hasNext()) {
                Reference ref = refs.next();
                Address fromAddr = ref.getFromAddress();
                Function func = funcMgr.getFunctionContaining(fromAddr);
                if (func != null) {
                    functions.add(func);
                }
            }
        }

        println("Found " + functions.size() + " functions referencing packed_data_collection strings");

        // Also find callers of these functions (one level up)
        Set<Function> callers = new LinkedHashSet<>();
        for (Function func : functions) {
            Address entryPoint = func.getEntryPoint();
            ReferenceIterator refs = refMgr.getReferencesTo(entryPoint);
            while (refs.hasNext()) {
                Reference ref = refs.next();
                if (ref.getReferenceType().isCall()) {
                    Function caller = funcMgr.getFunctionContaining(ref.getFromAddress());
                    if (caller != null && !functions.contains(caller)) {
                        callers.add(caller);
                    }
                }
            }
        }

        println("Found " + callers.size() + " direct callers");

        // Output file
        String outPath = System.getProperty("user.dir") + "/re/ghidra/decompiled-packed-data.txt";
        File outFile = new File(outPath);
        PrintWriter pw = new PrintWriter(outFile);

        pw.println("// ================================================================");
        pw.println("// Decompiled packed_data_collection functions");
        pw.println("// Saleae Logic 2 v2.4.40 - libgraph_server_shared.so");
        pw.println("// Generated by DecompilePackedData.java");
        pw.println("// ================================================================");
        pw.println();

        // Decompile core functions
        pw.println("// ================================================================");
        pw.println("// CORE FUNCTIONS (directly reference packed_data_collection sources)");
        pw.println("// ================================================================");
        pw.println();

        int count = 0;
        for (Function func : functions) {
            long elfVA = func.getEntryPoint().getOffset() - 0x100000L;
            pw.println("// ----------------------------------------------------------------");
            pw.println("// Function at Ghidra VA 0x" + Long.toHexString(func.getEntryPoint().getOffset()));
            pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
            pw.println("// Name: " + func.getName());
            pw.println("// Size: " + func.getBody().getNumAddresses() + " bytes");
            pw.println("// ----------------------------------------------------------------");

            DecompileResults results = decomp.decompileFunction(func, 60, monitor);
            if (results.decompileCompleted()) {
                pw.println(results.getDecompiledFunction().getC());
            } else {
                pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
            }
            pw.println();
            count++;
        }

        // Decompile callers
        pw.println("// ================================================================");
        pw.println("// CALLERS (one level up from core functions)");
        pw.println("// ================================================================");
        pw.println();

        for (Function func : callers) {
            long elfVA = func.getEntryPoint().getOffset() - 0x100000L;
            pw.println("// ----------------------------------------------------------------");
            pw.println("// Caller at Ghidra VA 0x" + Long.toHexString(func.getEntryPoint().getOffset()));
            pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
            pw.println("// Name: " + func.getName());
            pw.println("// Size: " + func.getBody().getNumAddresses() + " bytes");
            pw.println("// ----------------------------------------------------------------");

            DecompileResults results = decomp.decompileFunction(func, 60, monitor);
            if (results.decompileCompleted()) {
                pw.println(results.getDecompiledFunction().getC());
            } else {
                pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
            }
            pw.println();
            count++;
        }

        pw.close();
        decomp.dispose();
        println("Decompiled " + count + " functions to: " + outPath);
    }
}
