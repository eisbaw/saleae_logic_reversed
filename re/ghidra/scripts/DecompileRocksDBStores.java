// Decompile functions related to AnalogStore/DigitalStore RocksDB persistence
// @category Analysis
// @author claude

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.ReferenceIterator;
import ghidra.program.model.symbol.ReferenceManager;

import java.io.File;
import java.io.PrintWriter;
import java.util.LinkedHashSet;
import java.util.Set;

public class DecompileRocksDBStores extends GhidraScript {

    // Ghidra VAs (ELF VA + 0x100000) for strings referencing RocksDB store operations
    private static final long[] STRING_ADDRS = {
        // RocksDB error strings
        0x4eea30L, // "Failed to create RocksDB database: "
        0x4e7747L, // "Failed to write to RocksDB database: "
        0x4eea54L, // "Failed to flush RocksDB database: "

        // Database path config
        0x52e03dL, // "/databasePath"

        // AnalogStore serialization strings
        0x45592fL, // "AnalogStore::OnStartDeserialization: File not found - "
        0x4a59daL, // "AnalogStore::OnStartSerialization: Serialization exception encountered"
        0x4a5a21L, // "AnalogStore::CanStartSerialization: joining previous..."
        0x4e067aL, // "AnalogStore::OnStartDeserialization: Creating deserialization thread"
        0x4e06d3L, // "AnalogSerializer"

        // DigitalStore serialization strings
        0x455ad4L, // "DigitalStore::CanStartSerialization: failed..."
        0x469e70L, // "DigitalStore::OnStartSerialization: Creating serialization thread"
        0x482b5bL, // "DigitalStore::OnStartSerialization: {} opened"
        0x4899a2L, // "DigitalStore::OnStartSerialization: File not found - "
        0x4d8af7L, // "DigitalStore::OnStartSerialization: serialization complete..."
        0x4d8b41L, // "DigitalStore::OnStartDeserialization: Creating deserialization thread"

        // WaveformStoreNode (likely base class)
        0x4b69d2L, // "Saleae::Graph::WaveformStoreNode"
        0x4b69a2L, // "WaveformStoreNode::DeserializeOnThread: Done - "
        0x4b6967L, // "WaveformStoreNode::OnStartSerialization: File not found - "

        // serialize_data.h source path
        0x470640L, // "/workspace/monorepo/graph-io/core/saleae_base/include/serialize_data.h"
    };

    @Override
    public void run() throws Exception {
        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setSimplificationStyle("decompile");

        FunctionManager funcMgr = currentProgram.getFunctionManager();
        ReferenceManager refMgr = currentProgram.getReferenceManager();

        Set<Function> functions = new LinkedHashSet<>();

        // Find all functions referencing these strings
        for (long addr : STRING_ADDRS) {
            Address strAddr = toAddr(addr);
            ReferenceIterator refs = refMgr.getReferencesTo(strAddr);
            while (refs.hasNext()) {
                Reference ref = refs.next();
                Address fromAddr = ref.getFromAddress();
                Function func = funcMgr.getFunctionContaining(fromAddr);
                if (func != null) {
                    functions.add(func);
                }
            }
        }

        println("Found " + functions.size() + " functions referencing RocksDB store strings");

        // Also find callers of these functions (one level up)
        Set<Function> callers = new LinkedHashSet<>();
        for (Function func : functions) {
            Address entryPoint = func.getEntryPoint();
            ReferenceIterator refs = refMgr.getReferencesTo(entryPoint);
            while (refs.hasNext()) {
                Reference ref = refs.next();
                if (ref.getReferenceType().isCall()) {
                    Function caller = funcMgr.getFunctionContaining(ref.getFromAddress());
                    if (caller != null && !functions.contains(caller)) {
                        callers.add(caller);
                    }
                }
            }
        }

        println("Found " + callers.size() + " direct callers");

        // Output file
        String outPath = System.getProperty("user.dir") + "/re/ghidra/decompiled-rocksdb-stores.txt";
        File outFile = new File(outPath);
        PrintWriter pw = new PrintWriter(outFile);

        pw.println("// ================================================================");
        pw.println("// Decompiled RocksDB AnalogStore/DigitalStore persistence functions");
        pw.println("// Saleae Logic 2 v2.4.40 - libgraph_server_shared.so");
        pw.println("// Generated by DecompileRocksDBStores.java");
        pw.println("// ================================================================");
        pw.println();

        // Decompile core functions
        pw.println("// ================================================================");
        pw.println("// CORE FUNCTIONS (directly reference RocksDB strings)");
        pw.println("// ================================================================");
        pw.println();

        int count = 0;
        for (Function func : functions) {
            long elfVA = func.getEntryPoint().getOffset() - 0x100000L;
            pw.println("// ----------------------------------------------------------------");
            pw.println("// Function at Ghidra VA 0x" + Long.toHexString(func.getEntryPoint().getOffset()));
            pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
            pw.println("// Name: " + func.getName());
            pw.println("// Size: " + func.getBody().getNumAddresses() + " bytes");
            pw.println("// ----------------------------------------------------------------");

            DecompileResults results = decomp.decompileFunction(func, 120, monitor);
            if (results.decompileCompleted()) {
                pw.println(results.getDecompiledFunction().getC());
            } else {
                pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
            }
            pw.println();
            count++;
        }

        // Decompile callers
        pw.println("// ================================================================");
        pw.println("// CALLERS (one level up from core functions)");
        pw.println("// ================================================================");
        pw.println();

        for (Function func : callers) {
            long elfVA = func.getEntryPoint().getOffset() - 0x100000L;
            pw.println("// ----------------------------------------------------------------");
            pw.println("// Caller at Ghidra VA 0x" + Long.toHexString(func.getEntryPoint().getOffset()));
            pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
            pw.println("// Name: " + func.getName());
            pw.println("// Size: " + func.getBody().getNumAddresses() + " bytes");
            pw.println("// ----------------------------------------------------------------");

            DecompileResults results = decomp.decompileFunction(func, 120, monitor);
            if (results.decompileCompleted()) {
                pw.println(results.getDecompiledFunction().getC());
            } else {
                pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
            }
            pw.println();
            count++;
        }

        pw.close();
        decomp.dispose();
        println("Decompiled " + count + " functions to: " + outPath);
    }
}
