// Decompile the on_libusb_transfer_complete callback and the inner thread function.
// Find by xref to known strings.
//
// Usage: ghidra-analyzeHeadless <project_dir> <project_name> -process -noanalysis \
//   -scriptPath re/ghidra/scripts -postScript DecompileStreamingThread2.java
//
// @category USB

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;
import ghidra.program.model.mem.Memory;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.ReferenceIterator;

import java.io.FileWriter;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

public class DecompileStreamingThread2 extends GhidraScript {

    // Known string offsets in the binary (add 0x100000 for Ghidra VAs)
    // "on_libusb_transfer_complete" assertion string at file offset 0x377244
    // "bytes_transferred <= data_length" at 0x3dfc7e
    // "USB Transfer Error" at... search for it

    // Addresses to decompile directly (Ghidra VAs)
    private static final long[] ADDRESSES = {
        0x02e94ae0L,  // pthread target from ReadStream_QueueBuffersThread
    };

    // Strings whose xref functions we want to decompile
    private static final String[] TARGET_STRINGS = {
        "on_libusb_transfer_complete",
        "bytes_transferred <= data_length",
        "USB Transfer Error, expected transfer size",
        "Failed to submit USB transfer",
        "reducing queue capacity",
        "BulkReadThread: Waiting for memory",
    };

    @Override
    public void run() throws Exception {
        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setSimplificationStyle("decompile");

        FunctionManager fm = currentProgram.getFunctionManager();
        Memory mem = currentProgram.getMemory();
        Set<Address> seen = new HashSet<>();
        List<Function> targets = new ArrayList<>();

        // 1. Functions at known addresses
        for (long addr : ADDRESSES) {
            Address a = toAddr(addr);
            Function f = fm.getFunctionAt(a);
            if (f == null) f = fm.getFunctionContaining(a);
            if (f != null && seen.add(f.getEntryPoint())) {
                targets.add(f);
                println("Direct: " + f.getName() + " @ " + f.getEntryPoint());
            }
        }

        // 2. Find functions by string xref
        // Search through all defined strings for our targets
        for (ghidra.program.model.listing.Data data :
             ghidra.program.util.DefinedDataIterator.definedStrings(currentProgram)) {
            String val = data.getValue().toString();
            for (String target : TARGET_STRINGS) {
                if (val.contains(target)) {
                    // Find xrefs to this string
                    Address strAddr = data.getAddress();
                    for (Reference ref : getReferencesTo(strAddr)) {
                        Function f = fm.getFunctionContaining(ref.getFromAddress());
                        if (f != null && seen.add(f.getEntryPoint())) {
                            targets.add(f);
                            println("By string \"" + target + "\": " +
                                f.getName() + " @ " + f.getEntryPoint() +
                                " (" + f.getBody().getNumAddresses() + " bytes)");
                        }
                    }
                }
            }
        }

        println("Total to decompile: " + targets.size());

        // 3. Decompile
        String outPath = System.getProperty("user.home") +
            "/nvidia/saleae_reverse/re/ghidra/decompiled-streaming-thread2.txt";
        PrintWriter out = new PrintWriter(new FileWriter(outPath));

        out.println("// Decompiled streaming callback and support functions");
        out.println("// Generated by DecompileStreamingThread2.java");
        out.println("// " + new java.util.Date());
        out.println();

        for (Function f : targets) {
            out.println("// ========================================================================");
            out.println("// Function: " + f.getName());
            out.println("// Address:  " + f.getEntryPoint() +
                " (ELF VA: 0x" + Long.toHexString(f.getEntryPoint().getOffset() - 0x100000) + ")");
            out.println("// Size:     " + f.getBody().getNumAddresses() + " bytes");
            out.println("// ========================================================================");
            out.println();

            DecompileResults result = decomp.decompileFunction(f, 120, monitor);
            if (result.decompileCompleted()) {
                out.println(result.getDecompiledFunction().getC());
            } else {
                out.println("// DECOMPILATION FAILED: " + result.getErrorMessage());
            }
            out.println();
        }

        out.close();
        decomp.dispose();
        println("Output: " + outPath);
    }
}
