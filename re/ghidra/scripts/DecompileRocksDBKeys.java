// Decompile key serialization functions used by RocksDB stores
// @category Analysis
// @author claude

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionManager;

import java.io.File;
import java.io.PrintWriter;

public class DecompileRocksDBKeys extends GhidraScript {

    // Ghidra VAs for key serialization helper functions
    // These are called in sequence before each RocksDB Put() call
    private static final long[] FUNC_ADDRS = {
        // Key component serializers (called before RocksDB Put)
        0x1d9a280L, // FUN_01d9a280 - serialize key component 1 (tag/type byte?)
        0x1d99cb0L, // FUN_01d99cb0 - serialize key component 2 (string/channel?)
        0x1d9b2d0L, // FUN_01d9b2d0 - serialize key component 3 (data blob?)
        0x1c9a920L, // FUN_01c9a920 - serialize key component 4 (GraphTime i128?)

        // Additional serializers found in patterns
        0x1d9a130L, // FUN_01d9a130 - variant serializer

        // Key deserialization / iteration helpers
        0x1d8ed30L, // FUN_01d8ed30 - called with (buf, tag, 0xFF)

        // RocksDB database open/init
        0x1d89d50L, // FUN_01d89d50 - RocksDB DB::Open (references "Failed to create RocksDB database")

        // The RocksDB write functions themselves
        0x1d991b0L, // FUN_01d991b0 - RocksDB Put wrapper (analog data?)
        0x1d994b0L, // FUN_01d994b0 - RocksDB Put wrapper (digital data?)

        // RocksDB flush function
        0x1d8b2c0L, // FUN_01d8b2c0 - references "Failed to flush RocksDB database"
    };

    @Override
    public void run() throws Exception {
        DecompInterface decomp = new DecompInterface();
        decomp.openProgram(currentProgram);
        decomp.setSimplificationStyle("decompile");

        FunctionManager funcMgr = currentProgram.getFunctionManager();

        String outPath = System.getProperty("user.dir") + "/re/ghidra/decompiled-rocksdb-keys.txt";
        File outFile = new File(outPath);
        PrintWriter pw = new PrintWriter(outFile);

        pw.println("// ================================================================");
        pw.println("// Decompiled RocksDB key serialization functions");
        pw.println("// Saleae Logic 2 v2.4.40 - libgraph_server_shared.so");
        pw.println("// Generated by DecompileRocksDBKeys.java");
        pw.println("// ================================================================");
        pw.println();

        int count = 0;
        for (long addr : FUNC_ADDRS) {
            Address funcAddr = toAddr(addr);
            Function func = funcMgr.getFunctionAt(funcAddr);
            if (func == null) {
                pw.println("// WARNING: No function at Ghidra VA 0x" + Long.toHexString(addr));
                pw.println();
                continue;
            }

            long elfVA = func.getEntryPoint().getOffset() - 0x100000L;
            pw.println("// ----------------------------------------------------------------");
            pw.println("// Function at Ghidra VA 0x" + Long.toHexString(func.getEntryPoint().getOffset()));
            pw.println("// ELF VA: 0x" + Long.toHexString(elfVA));
            pw.println("// Name: " + func.getName());
            pw.println("// Size: " + func.getBody().getNumAddresses() + " bytes");
            pw.println("// ----------------------------------------------------------------");

            DecompileResults results = decomp.decompileFunction(func, 120, monitor);
            if (results.decompileCompleted()) {
                pw.println(results.getDecompiledFunction().getC());
            } else {
                pw.println("// DECOMPILE FAILED: " + results.getErrorMessage());
            }
            pw.println();
            count++;
        }

        pw.close();
        decomp.dispose();
        println("Decompiled " + count + " functions to: " + outPath);
    }
}
